-- Review/run once under an administrative deployment identity after budget preflight.
-- This script is not invoked by tests and does not create or convert an account.
CREATE ROLE IF NOT EXISTS LAB_DEVELOPER;
CREATE ROLE IF NOT EXISTS LAB_RUNTIME;
CREATE ROLE IF NOT EXISTS LAB_EVALUATOR;
CREATE ROLE IF NOT EXISTS LAB_NATIVE_EVALUATOR;
CREATE DATABASE IF NOT EXISTS AGENT_LAB;
CREATE SCHEMA IF NOT EXISTS AGENT_LAB.BENCHMARK_R1;
CREATE SCHEMA IF NOT EXISTS AGENT_LAB.SEMANTICS;
CREATE SCHEMA IF NOT EXISTS AGENT_LAB.AGENTS;
CREATE SCHEMA IF NOT EXISTS AGENT_LAB.EVAL_PRIVATE;
CREATE SCHEMA IF NOT EXISTS AGENT_LAB.EVAL_NATIVE;
CREATE SCHEMA IF NOT EXISTS AGENT_LAB.OBSERVABILITY;
CREATE WAREHOUSE IF NOT EXISTS LAB_XS
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 300 AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE MIN_CLUSTER_COUNT = 1 MAX_CLUSTER_COUNT = 1
  STATEMENT_TIMEOUT_IN_SECONDS = 60;

GRANT USAGE ON DATABASE AGENT_LAB TO ROLE LAB_RUNTIME;
GRANT USAGE ON SCHEMA AGENT_LAB.BENCHMARK_R1 TO ROLE LAB_RUNTIME;
GRANT USAGE ON SCHEMA AGENT_LAB.SEMANTICS TO ROLE LAB_RUNTIME;
GRANT USAGE ON SCHEMA AGENT_LAB.AGENTS TO ROLE LAB_RUNTIME;
GRANT USAGE ON WAREHOUSE LAB_XS TO ROLE LAB_RUNTIME;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_AGENT_USER TO ROLE LAB_RUNTIME;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_ANALYST_USER TO ROLE LAB_RUNTIME;

GRANT USAGE ON DATABASE AGENT_LAB TO ROLE LAB_DEVELOPER;
GRANT USAGE ON SCHEMA AGENT_LAB.BENCHMARK_R1 TO ROLE LAB_DEVELOPER;
GRANT USAGE ON SCHEMA AGENT_LAB.SEMANTICS TO ROLE LAB_DEVELOPER;
GRANT USAGE ON SCHEMA AGENT_LAB.AGENTS TO ROLE LAB_DEVELOPER;
GRANT CREATE SEMANTIC VIEW ON SCHEMA AGENT_LAB.SEMANTICS TO ROLE LAB_DEVELOPER;
GRANT CREATE AGENT ON SCHEMA AGENT_LAB.AGENTS TO ROLE LAB_DEVELOPER;
GRANT USAGE ON WAREHOUSE LAB_XS TO ROLE LAB_DEVELOPER;

GRANT USAGE ON DATABASE AGENT_LAB TO ROLE LAB_EVALUATOR;
GRANT USAGE ON SCHEMA AGENT_LAB.EVAL_PRIVATE TO ROLE LAB_EVALUATOR;
GRANT CREATE TABLE ON SCHEMA AGENT_LAB.EVAL_PRIVATE TO ROLE LAB_EVALUATOR;
GRANT USAGE ON SCHEMA AGENT_LAB.OBSERVABILITY TO ROLE LAB_EVALUATOR;
GRANT CREATE TABLE ON SCHEMA AGENT_LAB.OBSERVABILITY TO ROLE LAB_EVALUATOR;
GRANT USAGE ON WAREHOUSE LAB_XS TO ROLE LAB_EVALUATOR;

-- TRAIN-only native diagnostic role; it never receives EVAL_PRIVATE permissions.
GRANT ROLE LAB_RUNTIME TO ROLE LAB_NATIVE_EVALUATOR;
GRANT USAGE ON SCHEMA AGENT_LAB.EVAL_NATIVE TO ROLE LAB_NATIVE_EVALUATOR;
GRANT CREATE TABLE, CREATE DATASET, CREATE STAGE ON SCHEMA AGENT_LAB.EVAL_NATIVE
  TO ROLE LAB_NATIVE_EVALUATOR;

-- Grant SELECT on each frozen table/view and USAGE on the specific agent after
-- deployment. No broad future grants; no evaluator role inheritance for runtime.
